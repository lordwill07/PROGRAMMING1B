    private void jProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jProcessActionPerformed
        // TODO add your handling code here:
        
    try {
        //capture inputs
        String customerName = txtName.getText();
        String product = cmbProduct.getSelectedItem().toString();
        double price = Double.parseDouble(txtPrice.getText());

        // Use the calculations class
        ProductCalculations calc = new ProductCalculations(price);
        double vat = calc.GetVat();
        double commission = calc.GetCommission();
        double total = calc.GetTotal();

        //Show in Message Box 
        String output = "Customer Name: " + customerName +
                "\nProduct: " + product +
                "\nVAT: R " + vat +
                "\nCOMMISSION: R " + commission +
                "\nTOTAL: R " + total;
        JOptionPane.showMessageDialog(this, output);

        //Save to data.txt
        try {
            FileWriter writer = new FileWriter("data.txt");
            writer.write("DATA LOG\n");
            writer.write("******************************************\n");
            writer.write("Customer Name: " + customerName + "\n");
            writer.write("Product: " + product + "\n");
            writer.write("VAT: R " + vat + "\n");
            writer.write("COMMISSION: R " + commission + "\n");
            writer.write("TOTAL: R " + total + "\n");
            writer.write("******************************************");
            writer.close();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error saving file: " + e.getMessage());
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter a valid price!");
    }

        
    }//GEN-LAST:event_jProcessActionPerformed

